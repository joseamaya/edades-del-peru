#!/usr/bin/env python3
"""Generate the authored Moche valley heightfield (m3, 192 m map)."""

from __future__ import annotations

import base64
import math
from pathlib import Path

SIZE = 192
N = SIZE + 1
SITE_Y = 6.0
COAST = 1.0
BEACH = 1.9
VALLEY = 3.2
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/model/defs/mocheHeightmap.ts'


def smoothstep(a: float, b: float, x: float) -> float:
    t = max(0.0, min(1.0, (x - a) / (b - a)))
    return t * t * (3.0 - 2.0 * t)


def noise(x: float, z: float) -> float:
    return (
        math.sin(x * 0.17 + z * 0.12) * 0.22
        + math.sin(x * 0.053 - z * 0.16 + 1.1) * 0.14
        + math.sin(x * 0.31 + z * 0.27 + 0.5) * 0.06
    )


def height(x: float, z: float) -> float:
    # Pacific shore in the west, irrigated valley and the Huacas terrace inland.
    if x < 16.0:
        h = COAST
    elif x < 25.0:
        h = COAST + (BEACH - COAST) * smoothstep(16.0, 25.0, x)
    else:
        h = VALLEY + 0.15 * noise(x, z)

    # The Huacas de Moche and the player's valley base are broad flat terraces.
    site = smoothstep(87.0, 96.0, x) * (1.0 - smoothstep(147.0, 156.0, x))
    site *= smoothstep(42.0, 51.0, z) * (1.0 - smoothstep(103.0, 112.0, z))
    base = smoothstep(39.0, 47.0, x) * (1.0 - smoothstep(77.0, 85.0, x))
    base *= smoothstep(108.0, 116.0, z) * (1.0 - smoothstep(139.0, 147.0, z))
    flat = max(site, base)
    h = h * (1.0 - 0.94 * flat) + SITE_Y * (0.94 * flat)

    # Andean foothills east of the valley and low dunes north/south.
    east = smoothstep(145.0, 180.0, x) * (10.0 + 3.0 * math.sin(z * 0.1 + 0.8))
    north = smoothstep(16.0, 0.0, z) * (2.0 + 1.2 * math.sin(x * 0.12))
    south = smoothstep(158.0, 188.0, z) * (3.0 + 1.5 * math.sin(x * 0.13 + 0.6))
    h += east + north + south

    # A shallow dry quebrada east of the huacas.
    h -= 1.2 * math.exp(-((x - 151.0) / 5.5) ** 2) * smoothstep(52.0, 70.0, z) * (1.0 - smoothstep(105.0, 125.0, z))
    return max(0.9, h)


values = []
for iz in range(N):
    z = iz * SIZE / (N - 1)
    for ix in range(N):
        x = ix * SIZE / (N - 1)
        values.append(round(height(x, z) * 1000.0))

raw = bytearray()
for v in values:
    raw.extend(int(v).to_bytes(2, 'little'))
b64 = base64.b64encode(raw).decode('ascii')

OUT.write_text(
    '// Generated by scripts/build_moche_heightmap.py. Do not edit by hand.\n'
    'export const MOCHE_HEIGHTMAP_SIZE = ' + str(N) + ';\n'
    'export const MOCHE_HEIGHTMAP_WORLD_SIZE = ' + str(SIZE) + ';\n'
    'export const MOCHE_HEIGHTMAP_SCALE = 0.001;\n'
    'const B64 =\n  \'' + b64 + '\';\n'
    'function decode(): Float32Array {\n'
    '  const bin = atob(B64);\n'
    '  const out = new Float32Array(' + str(len(values)) + ');\n'
    '  for (let i = 0; i < out.length; i++) {\n'
    '    out[i] = (bin.charCodeAt(i * 2) | (bin.charCodeAt(i * 2 + 1) << 8)) * MOCHE_HEIGHTMAP_SCALE;\n'
    '  }\n'
    '  return out;\n'
    '}\n'
    'export const MOCHE_HEIGHTMAP = decode();\n',
    encoding='utf-8',
)
print(f'wrote {OUT} ({len(b64)} base64 chars, {len(values)} samples)')
