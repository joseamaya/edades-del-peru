#!/usr/bin/env python3
"""Generate the Phase 1 mission-scoped heightfields.

These fields are applied through `MissionSite.heightField` on top of an existing authored site:
the site model and anchors stay stable, the terrain geometry changes per mission.
"""

from __future__ import annotations

import base64
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/model/defs'


def smooth(a: float, b: float, x: float) -> float:
    t = max(0.0, min(1.0, (x - a) / (b - a)))
    return t * t * (3.0 - 2.0 * t)


def noise(x: float, z: float) -> float:
    return (
        math.sin(x * 0.071 + z * 0.113 + 0.4) * 0.35
        + math.sin(x * 0.19 - z * 0.23 + 1.7) * 0.2
        + math.sin(x * 0.41 + z * 0.37) * 0.1
    )


def encode(values: list[int]) -> str:
    raw = bytearray()
    prev = 0
    for value in values:
        delta = int(value) - prev
        prev = int(value)
        zigzag = (delta << 1) ^ (delta >> 31)
        while zigzag >= 0x80:
            raw.append((zigzag & 0x7F) | 0x80)
            zigzag >>= 7
        raw.append(zigzag)
    return base64.b64encode(raw).decode('ascii')


def write(name: str, size: int, fn) -> None:
    values = []
    for z in range(size):
        for x in range(size):
            values.append(max(300, round(fn(x / (size - 1) * 256.0, z / (size - 1) * 256.0) * 1000)))
    b64 = encode(values)
    key = name.upper()
    text = (
        f'// Generated by scripts/build_geographic_heightmaps.py. Do not edit by hand.\n'
        f"import {{ decodeHeightmap }} from './heightmapCodec';\n"
        f"import type {{ AuthoredHeightField }} from './authoredTerrain';\n"
        f'export const {key}_HEIGHTMAP_SIZE = {size};\n'
        f'export const {key}_HEIGHTMAP_WORLD_SIZE = 256;\n'
        f'export const {key}_HEIGHTMAP_SCALE = 0.001;\n'
        f"const B64 =\n  '{b64}';\n"
        f'export const {key}_HEIGHTMAP = decodeHeightmap(B64, {len(values)}, {key}_HEIGHTMAP_SCALE);\n'
        f'export const {key}_HEIGHTFIELD: AuthoredHeightField = {{\n'
        f'  size: {key}_HEIGHTMAP_SIZE,\n'
        f'  worldSize: {key}_HEIGHTMAP_WORLD_SIZE,\n'
        f'  heights: {key}_HEIGHTMAP,\n'
        f'}};\n'
    )
    (OUT / f'{name}Heightmap.ts').write_text(text)
    print(f'wrote {name} ({size}x{size}, {len(b64)} base64 chars)')


def quipaipan(x: float, z: float) -> float:
    h = 5.1 + 0.22 * noise(x, z)
    h += 2.4 * (1.0 - smooth(0.0, 1.0, math.hypot((x - 78) / 40, (z - 178) / 34)))
    h += 1.8 * (1.0 - smooth(0.0, 1.0, math.hypot((x - 184) / 46, (z - 74) / 38)))
    wash = math.exp(-((z - 128) / 9.0) ** 2) * smooth(36, 60, x) * (1 - smooth(190, 220, x))
    h -= wash * 1.1
    h += smooth(224, 256, z) * 7 + smooth(232, 256, x) * 6
    return max(2.7, h)


def tarapaca(x: float, z: float) -> float:
    h = 6.4 + 0.3 * noise(x, z)
    canyon = math.exp(-((z - 132) / 17.0) ** 2) * smooth(30, 60, x) * (1 - smooth(200, 232, x))
    h = h * (1 - canyon) + 2.8 * canyon
    oasis = 1 - smooth(8, 22, math.hypot(x - 92, z - 140))
    h = h * (1 - oasis) + 4.6 * oasis
    h += smooth(226, 256, z) * 7 + smooth(226, 256, x) * 6
    return max(2.6, h)


def vilcabamba(x: float, z: float) -> float:
    h = 8.0 + 0.5 * noise(x, z)
    h += 7.0 * (0.5 + 0.5 * math.sin(x * 0.045 + 1.1)) * smooth(30, 70, x)
    h += 5.0 * (0.5 + 0.5 * math.sin(z * 0.05 + 0.3))
    river = math.exp(-((x - 132) / 13.0) ** 2)
    h = h * (1 - river) + 1.0 * river
    bank = math.exp(-((x - 132) / 34.0) ** 2)
    h = h * (1 - bank) + 2.8 * bank
    h += smooth(232, 256, z) * 10
    return max(0.9, h)


def mantaro(x: float, z: float) -> float:
    h = 4.2 + 0.35 * noise(x, z)
    valley = math.exp(-((x - 128) / 34.0) ** 2)
    h = h * (1 - valley) + 3.0 * valley
    river = math.exp(-((x - 128) / 7.0) ** 2)
    h = h * (1 - river) + 1.0 * river
    terraces = math.sin(x * 0.11) * 0.8
    h += terraces * smooth(60, 100, x) * (1 - smooth(156, 196, x))
    h += smooth(0, 28, 28 - x) * 9 + smooth(228, 256, x) * 10
    h += smooth(232, 256, z) * 8 + smooth(0, 24, 24 - z) * 7
    return max(0.9, h)


def lima1821(x: float, z: float) -> float:
    h = 4.6 + 0.25 * noise(x, z)
    sea = 1 - smooth(18, 32, x)
    h = h * (1 - sea) + 0.4 * sea
    h += smooth(204, 256, x) * 7
    h += smooth(0, 30, 30 - z) * 2.0
    river = math.exp(-((z - 126) / 8.0) ** 2) * smooth(30, 42, x)
    h = h * (1 - river) + 1.0 * river
    city = 1 - smooth(20, 54, math.hypot(x - 92, z - 160))
    h = h * (1 - city) + 5.2 * city
    return max(0.4, h)


def miraflores(x: float, z: float) -> float:
    h = 4.5 + 0.25 * noise(x, z)
    sea = 1 - smooth(16, 30, x)
    h = h * (1 - sea) + 0.4 * sea
    h += 1.2 * math.exp(-((z - 94) / 7.0) ** 2)
    h += smooth(214, 256, x) * 6
    h += smooth(0, 28, 28 - z) * 2.0
    return max(0.4, h)


def callao(x: float, z: float) -> float:
    h = 3.8 + 0.2 * noise(x, z)
    bay = 1 - smooth(26, 44, x + (z - 70) * 0.15)
    h = h * (1 - bay) + 0.4 * bay
    fort = 1 - smooth(9, 20, math.hypot(x - 92, z - 74))
    h = h * (1 - fort) + 5.0 * fort
    h += smooth(208, 256, x) * 5
    return max(0.4, h)


if __name__ == '__main__':
    write('quipaipan', 257, quipaipan)
    write('tarapaca', 257, tarapaca)
    write('vilcabamba', 257, vilcabamba)
    write('mantaro', 257, mantaro)
    write('lima1821', 129, lima1821)
    write('miraflores', 129, miraflores)
    write('callao', 129, callao)
