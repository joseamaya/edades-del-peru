#!/usr/bin/env python3
"""Generate the authored Yahuar Pampa / Chanca heightfield (m5, 160 m map)."""

from __future__ import annotations

import base64
import math
from pathlib import Path

SIZE = 160
N = SIZE + 1
SITE_Y = 5.0
VALLEY = 3.2
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/model/defs/chancaHeightmap.ts'


def smoothstep(a: float, b: float, x: float) -> float:
    t = max(0.0, min(1.0, (x - a) / (b - a)))
    return t * t * (3.0 - 2.0 * t)


def noise(x: float, z: float) -> float:
    return (
        math.sin(x * 0.21 + z * 0.15) * 0.24
        + math.sin(x * 0.063 - z * 0.17 + 1.4) * 0.15
        + math.sin(x * 0.35 + z * 0.29 + 0.6) * 0.06
    )


def height(x: float, z: float) -> float:
    # High pampa with a shallow valley between Cusco and the Chanca heights.
    h = VALLEY + 0.22 * noise(x, z)
    valley = math.exp(-((z - 82.0) / 10.0) ** 2) * smoothstep(28.0, 52.0, x) * (1.0 - smoothstep(112.0, 136.0, x))
    h -= valley * 1.5

    # Cusco base, the Chanca fortress terrace and the approach pampa stay flat.
    base = smoothstep(38.0, 46.0, x) * (1.0 - smoothstep(75.0, 83.0, x))
    base *= smoothstep(82.0, 90.0, z) * (1.0 - smoothstep(114.0, 122.0, z))
    site = smoothstep(96.0, 104.0, x) * (1.0 - smoothstep(126.0, 134.0, x))
    site *= smoothstep(44.0, 52.0, z) * (1.0 - smoothstep(78.0, 86.0, z))
    approach = smoothstep(66.0, 74.0, x) * (1.0 - smoothstep(104.0, 112.0, x))
    approach *= smoothstep(62.0, 70.0, z) * (1.0 - smoothstep(98.0, 106.0, z))
    flat = max(base, site, approach)
    h = h * (1.0 - flat) + SITE_Y * flat

    # Andean ridges frame the pampa; the west stays open toward Cusco.
    north = smoothstep(14.0, 0.0, z) * (9.0 + 2.4 * math.sin(x * 0.1))
    east = smoothstep(128.0, 158.0, x) * (10.0 + 3.0 * math.sin(z * 0.11 + 0.9))
    south = smoothstep(128.0, 158.0, z) * (8.0 + 2.4 * math.sin(x * 0.12 + 0.4))
    west = smoothstep(24.0, 8.0, x) * (5.0 + 1.6 * math.sin(z * 0.13 + 0.7))
    h += north + east + south + west

    # A dry quebrada north-east of the fortress.
    h -= 1.1 * math.exp(-((x - 136.0) / 5.0) ** 2) * smoothstep(30.0, 48.0, z) * (1.0 - smoothstep(72.0, 92.0, z))
    return max(0.9, h)


values = []
for iz in range(N):
    z = iz * SIZE / (N - 1)
    for ix in range(N):
        x = ix * SIZE / (N - 1)
        values.append(round(height(x, z) * 1000.0))

raw = bytearray()
for v in values:
    raw.extend(int(v).to_bytes(2, 'little'))
b64 = base64.b64encode(raw).decode('ascii')

OUT.write_text(
    '// Generated by scripts/build_chanca_heightmap.py. Do not edit by hand.\n'
    'export const CHANCA_HEIGHTMAP_SIZE = ' + str(N) + ';\n'
    'export const CHANCA_HEIGHTMAP_WORLD_SIZE = ' + str(SIZE) + ';\n'
    'export const CHANCA_HEIGHTMAP_SCALE = 0.001;\n'
    'const B64 =\n  \'' + b64 + '\';\n'
    'function decode(): Float32Array {\n'
    '  const bin = atob(B64);\n'
    '  const out = new Float32Array(' + str(len(values)) + ');\n'
    '  for (let i = 0; i < out.length; i++) {\n'
    '    out[i] = (bin.charCodeAt(i * 2) | (bin.charCodeAt(i * 2 + 1) << 8)) * CHANCA_HEIGHTMAP_SCALE;\n'
    '  }\n'
    '  return out;\n'
    '}\n'
    'export const CHANCA_HEIGHTMAP = decode();\n',
    encoding='utf-8',
)
print(f'wrote {OUT} ({len(b64)} base64 chars, {len(values)} samples)')
