#!/usr/bin/env python3
"""Generate the authored Junín–Ayacucho heightfield (m8, 192 m map)."""

from __future__ import annotations

import base64
import math
from pathlib import Path

SIZE = 192
N = SIZE + 1
SITE_Y = 5.0
VALLEY = 3.2
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/model/defs/independenceHeightmap.ts'


def smoothstep(a: float, b: float, x: float) -> float:
    t = max(0.0, min(1.0, (x - a) / (b - a)))
    return t * t * (3.0 - 2.0 * t)


def noise(x: float, z: float) -> float:
    return (
        math.sin(x * 0.18 + z * 0.13) * 0.22
        + math.sin(x * 0.061 - z * 0.17 + 1.2) * 0.14
        + math.sin(x * 0.34 + z * 0.25 + 0.5) * 0.06
    )


def height(x: float, z: float) -> float:
    h = VALLEY + 0.2 * noise(x, z)
    base = smoothstep(45.0, 53.0, x) * (1.0 - smoothstep(84.0, 92.0, x))
    base *= smoothstep(105.0, 113.0, z) * (1.0 - smoothstep(137.0, 145.0, z))
    site = smoothstep(122.0, 130.0, x) * (1.0 - smoothstep(152.0, 160.0, x))
    site *= smoothstep(55.0, 63.0, z) * (1.0 - smoothstep(86.0, 94.0, z))
    approach = smoothstep(84.0, 92.0, x) * (1.0 - smoothstep(128.0, 136.0, x))
    approach *= smoothstep(78.0, 86.0, z) * (1.0 - smoothstep(112.0, 120.0, z))
    flat = max(base, site, approach)
    h = h * (1.0 - flat) + SITE_Y * flat

    north = smoothstep(15.0, 0.0, z) * (9.0 + 2.4 * math.sin(x * 0.1))
    east = smoothstep(154.0, 184.0, x) * (11.0 + 3.0 * math.sin(z * 0.11 + 0.9))
    south = smoothstep(154.0, 186.0, z) * (8.0 + 2.4 * math.sin(x * 0.12 + 0.4))
    west = smoothstep(24.0, 8.0, x) * (5.0 + 1.6 * math.sin(z * 0.13 + 0.7))
    h += north + east + south + west
    h -= 1.0 * math.exp(-((x - 151.0) / 5.0) ** 2) * smoothstep(50.0, 68.0, z) * (1.0 - smoothstep(94.0, 114.0, z))
    return max(0.9, h)


values = []
for iz in range(N):
    z = iz * SIZE / (N - 1)
    for ix in range(N):
        x = ix * SIZE / (N - 1)
        values.append(round(height(x, z) * 1000.0))

raw = bytearray()
for v in values:
    raw.extend(int(v).to_bytes(2, 'little'))
b64 = base64.b64encode(raw).decode('ascii')

OUT.write_text(
    '// Generated by scripts/build_independence_heightmap.py. Do not edit by hand.\n'
    'export const INDEPENDENCE_HEIGHTMAP_SIZE = ' + str(N) + ';\n'
    'export const INDEPENDENCE_HEIGHTMAP_WORLD_SIZE = ' + str(SIZE) + ';\n'
    'export const INDEPENDENCE_HEIGHTMAP_SCALE = 0.001;\n'
    'const B64 =\n  \'' + b64 + '\';\n'
    'function decode(): Float32Array {\n'
    '  const bin = atob(B64);\n'
    '  const out = new Float32Array(' + str(len(values)) + ');\n'
    '  for (let i = 0; i < out.length; i++) {\n'
    '    out[i] = (bin.charCodeAt(i * 2) | (bin.charCodeAt(i * 2 + 1) << 8)) * INDEPENDENCE_HEIGHTMAP_SCALE;\n'
    '  }\n'
    '  return out;\n'
    '}\n'
    'export const INDEPENDENCE_HEIGHTMAP = decode();\n',
    encoding='utf-8',
)
print(f'wrote {OUT} ({len(b64)} base64 chars, {len(values)} samples)')
