#!/usr/bin/env python3
"""Generate the authored Arica port heightfield (m9, 192 m map)."""

from __future__ import annotations

import base64
import math
from pathlib import Path

SIZE = 192
N = SIZE + 1
SITE_Y = 4.0
COAST = 0.8
BEACH = 1.7
TERRACE = 4.0
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/model/defs/aricaHeightmap.ts'


def smoothstep(a: float, b: float, x: float) -> float:
    t = max(0.0, min(1.0, (x - a) / (b - a)))
    return t * t * (3.0 - 2.0 * t)


def noise(x: float, z: float) -> float:
    return (
        math.sin(x * 0.18 + z * 0.12) * 0.14
        + math.sin(x * 0.051 - z * 0.15 + 1.1) * 0.09
        + math.sin(x * 0.29 + z * 0.24 + 0.4) * 0.04
    )


def height(x: float, z: float) -> float:
    if x < 18.0:
        h = COAST
    elif x < 28.0:
        h = COAST + (BEACH - COAST) * smoothstep(18.0, 28.0, x)
    else:
        h = 2.6 + 0.12 * noise(x, z)

    base = smoothstep(52.0, 60.0, x) * (1.0 - smoothstep(92.0, 100.0, x))
    base *= smoothstep(98.0, 106.0, z) * (1.0 - smoothstep(132.0, 140.0, z))
    site = smoothstep(116.0, 124.0, x) * (1.0 - smoothstep(154.0, 162.0, x))
    site *= smoothstep(53.0, 61.0, z) * (1.0 - smoothstep(85.0, 93.0, z))
    approach = smoothstep(88.0, 96.0, x) * (1.0 - smoothstep(124.0, 132.0, x))
    approach *= smoothstep(78.0, 86.0, z) * (1.0 - smoothstep(112.0, 120.0, z))
    flat = max(base, site, approach)
    h = h * (1.0 - flat) + TERRACE * flat

    # The Morro is outside the playable height range; a low coastal ridge frames it.
    east = smoothstep(156.0, 186.0, x) * (7.0 + 2.0 * math.sin(z * 0.1 + 0.8))
    north = smoothstep(16.0, 0.0, z) * (1.8 + 0.8 * math.sin(x * 0.11))
    south = smoothstep(158.0, 188.0, z) * (3.0 + 1.2 * math.sin(x * 0.12 + 0.5))
    h += east + north + south
    h -= 0.4 * math.exp(-((z - 105.0) / 3.0) ** 2) * smoothstep(90.0, 108.0, x) * (1.0 - smoothstep(138.0, 156.0, x))
    return max(0.7, h)


values = []
for iz in range(N):
    z = iz * SIZE / (N - 1)
    for ix in range(N):
        x = ix * SIZE / (N - 1)
        values.append(round(height(x, z) * 1000.0))

raw = bytearray()
for v in values:
    raw.extend(int(v).to_bytes(2, 'little'))
b64 = base64.b64encode(raw).decode('ascii')

OUT.write_text(
    '// Generated by scripts/build_arica_heightmap.py. Do not edit by hand.\n'
    'export const ARICA_HEIGHTMAP_SIZE = ' + str(N) + ';\n'
    'export const ARICA_HEIGHTMAP_WORLD_SIZE = ' + str(SIZE) + ';\n'
    'export const ARICA_HEIGHTMAP_SCALE = 0.001;\n'
    'const B64 =\n  \'' + b64 + '\';\n'
    'function decode(): Float32Array {\n'
    '  const bin = atob(B64);\n'
    '  const out = new Float32Array(' + str(len(values)) + ');\n'
    '  for (let i = 0; i < out.length; i++) {\n'
    '    out[i] = (bin.charCodeAt(i * 2) | (bin.charCodeAt(i * 2 + 1) << 8)) * ARICA_HEIGHTMAP_SCALE;\n'
    '  }\n'
    '  return out;\n'
    '}\n'
    'export const ARICA_HEIGHTMAP = decode();\n',
    encoding='utf-8',
)
print(f'wrote {OUT} ({len(b64)} base64 chars, {len(values)} samples)')
