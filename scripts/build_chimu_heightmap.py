#!/usr/bin/env python3
"""Generate the authored Chimú / Chan Chan heightfield (m6, 256 m map)."""

from __future__ import annotations

import base64
import math
from pathlib import Path

SIZE = 256
# The composition was authored for the former 192 m map; sample it 4/3 larger on the 256 m transect.
SOURCE_SIZE = 192
N = SIZE + 1
GROUND_SIZE = 128
SITE_Y = 5.0
COAST = 1.0
BEACH = 1.9
VALLEY = 3.0
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/model/defs/chimuHeightmap.ts'


def smoothstep(a: float, b: float, x: float) -> float:
    t = max(0.0, min(1.0, (x - a) / (b - a)))
    return t * t * (3.0 - 2.0 * t)


def noise(x: float, z: float) -> float:
    return (
        math.sin(x * 0.18 + z * 0.12) * 0.2
        + math.sin(x * 0.057 - z * 0.16 + 1.2) * 0.13
        + math.sin(x * 0.33 + z * 0.27 + 0.5) * 0.06
    )


def height(x: float, z: float) -> float:
    if x < 15.0:
        h = COAST
    elif x < 24.0:
        h = COAST + (BEACH - COAST) * smoothstep(15.0, 24.0, x)
    else:
        h = VALLEY + 0.15 * noise(x, z)

    base = smoothstep(48.0, 56.0, x) * (1.0 - smoothstep(84.0, 92.0, x))
    base *= smoothstep(104.0, 112.0, z) * (1.0 - smoothstep(134.0, 142.0, z))
    site = smoothstep(126.0, 134.0, x) * (1.0 - smoothstep(158.0, 166.0, x))
    site *= smoothstep(46.0, 54.0, z) * (1.0 - smoothstep(78.0, 86.0, z))
    approach = smoothstep(84.0, 92.0, x) * (1.0 - smoothstep(130.0, 138.0, x))
    approach *= smoothstep(66.0, 74.0, z) * (1.0 - smoothstep(98.0, 106.0, z))
    flat = max(base, site, approach)
    h = h * (1.0 - flat) + SITE_Y * flat

    east = smoothstep(158.0, 186.0, x) * (8.0 + 2.4 * math.sin(z * 0.1 + 0.9))
    north = smoothstep(16.0, 0.0, z) * (2.5 + 1.2 * math.sin(x * 0.11))
    south = smoothstep(158.0, 188.0, z) * (4.0 + 1.8 * math.sin(x * 0.12 + 0.5))
    h += east + north + south

    # The canal corridor stays low and readable without becoming a wall.
    h -= 0.5 * math.exp(-((z - 96.0) / 3.0) ** 2) * smoothstep(84.0, 100.0, x) * (1.0 - smoothstep(136.0, 154.0, x))
    return max(0.9, h)


def ground_weights(x: float, z: float) -> tuple[float, float, float, float]:
    """Painted ground weights (grass, dirt, sand, rock) in the former 192 m frame."""
    beach = 1.0 - smoothstep(24.0, 34.0, x)
    base = smoothstep(48.0, 56.0, x) * (1.0 - smoothstep(84.0, 92.0, x))
    base *= smoothstep(104.0, 112.0, z) * (1.0 - smoothstep(134.0, 142.0, z))
    site = smoothstep(126.0, 134.0, x) * (1.0 - smoothstep(158.0, 166.0, x))
    site *= smoothstep(46.0, 54.0, z) * (1.0 - smoothstep(78.0, 86.0, z))
    approach = smoothstep(84.0, 92.0, x) * (1.0 - smoothstep(130.0, 138.0, x))
    approach *= smoothstep(66.0, 74.0, z) * (1.0 - smoothstep(98.0, 106.0, z))
    terrace = max(base, site, approach)
    east = smoothstep(158.0, 186.0, x)
    canal = math.exp(-((z - 96.0) / 3.0) ** 2) * smoothstep(84.0, 100.0, x) * (1.0 - smoothstep(136.0, 154.0, x))
    dune = max(smoothstep(16.0, 0.0, z), smoothstep(158.0, 192.0, z))
    mottle = 0.85 + 0.3 * (0.5 + 0.5 * math.sin(x * 0.11 + 0.8) * math.sin(z * 0.09 + 0.4))

    sand = max(0.03, beach * 1.1 + dune * 0.8 + canal * 0.3)
    dirt = max(0.04, terrace * 0.9 + canal * 0.35 + (1.0 - beach) * 0.1)
    rock = max(0.02, east * 1.1)
    grass = max(0.02, (1.0 - beach) * (1.0 - east) * (1.0 - terrace * 0.5) * 0.9 * mottle)
    total = grass + dirt + sand + rock
    return (grass / total, dirt / total, sand / total, rock / total)


ground_values = []
# Texel centres at 2 m, matching `sampleAuthoredGround` (0..SIZE corners would shift the paint 1 m).
for iz in range(GROUND_SIZE):
    z = (iz + 0.5) * SIZE / GROUND_SIZE
    for ix in range(GROUND_SIZE):
        x = (ix + 0.5) * SIZE / GROUND_SIZE
        weights = ground_weights(x * SOURCE_SIZE / SIZE, z * SOURCE_SIZE / SIZE)
        for w in weights:
            ground_values.append(max(0, min(255, round(w * 255))))

ground_b64 = base64.b64encode(bytearray(ground_values)).decode('ascii')

values = []
for iz in range(N):
    z = iz * SIZE / (N - 1)
    for ix in range(N):
        x = ix * SIZE / (N - 1)
        values.append(round(height(x * SOURCE_SIZE / SIZE, z * SOURCE_SIZE / SIZE) * 1000.0))

raw = bytearray()
for v in values:
    raw.extend(int(v).to_bytes(2, 'little'))
b64 = base64.b64encode(raw).decode('ascii')

OUT.write_text(
    '// Generated by scripts/build_chimu_heightmap.py. Do not edit by hand.\n'
    'export const CHIMU_HEIGHTMAP_SIZE = ' + str(N) + ';\n'
    'export const CHIMU_HEIGHTMAP_WORLD_SIZE = ' + str(SIZE) + ';\n'
    'export const CHIMU_HEIGHTMAP_SCALE = 0.001;\n'
    'const B64 =\n  \'' + b64 + '\';\n'
    'function decode(): Float32Array {\n'
    '  const bin = atob(B64);\n'
    '  const out = new Float32Array(' + str(len(values)) + ');\n'
    '  for (let i = 0; i < out.length; i++) {\n'
    '    out[i] = (bin.charCodeAt(i * 2) | (bin.charCodeAt(i * 2 + 1) << 8)) * CHIMU_HEIGHTMAP_SCALE;\n'
    '  }\n'
    '  return out;\n'
    '}\n'
    'export const CHIMU_HEIGHTMAP = decode();\n'
    'export const CHIMU_GROUND_SIZE = ' + str(GROUND_SIZE) + ';\n'
    'const GROUND_B64 =\n  \'' + ground_b64 + '\';\n'
    'function decodeGround(): Uint8Array {\n'
    '  const bin = atob(GROUND_B64);\n'
    '  const out = new Uint8Array(' + str(len(ground_values)) + ');\n'
    '  for (let i = 0; i < out.length; i++) out[i] = bin.charCodeAt(i);\n'
    '  return out;\n'
    '}\n'
    'export const CHIMU_GROUND = decodeGround();\n',
    encoding='utf-8',
)
print(f'wrote {OUT} ({len(b64)} base64 chars, {len(values)} samples)')
