import type { MissionDef } from '../src/campaign/types';

export interface ChecklistOptions {
  /** One mission id, or empty for the whole campaign. */
  only?: string;
}

const list = (items: string[]): string => (items.length ? items.join('; ') : '—');

/**
 * The derived facts a mission contributes to the human checklist. Kept apart from the file output so the unit
 * test can assert them without running the script.
 *
 * Victory needs at least one non-optional objective: a `group` member counts, because the group is satisfied by
 * any member (`Mission.evalObjectives`). Grouped goals are listed apart only so the tester knows they are
 * alternatives.
 */
export function missionBrief(mission: MissionDef): {
  required: string[];
  grouped: string[];
  optional: string[];
  fires: number;
  strikes: number;
  withdrawals: number;
} {
  const strikes = (mission.triggers ?? []).flatMap((trigger) =>
    trigger.effects.filter((effect) => effect.type === 'strike'),
  );
  const withdrawals = (mission.triggers ?? []).flatMap((trigger) =>
    trigger.effects.filter((effect) => effect.type === 'withdraw'),
  );
  const winnable = mission.objectives.filter((objective) => !objective.optional);
  return {
    required: winnable.filter((objective) => !objective.group).map((objective) => objective.title),
    grouped: winnable.filter((objective) => objective.group).map((objective) => objective.title),
    optional: mission.objectives.filter((objective) => objective.optional).map((objective) => objective.title),
    fires: mission.fires?.length ?? 0,
    strikes: strikes.length,
    withdrawals: withdrawals.length,
  };
}

/** The checklist as Markdown, generated from the missions themselves. */
export function buildChecklist(missions: MissionDef[], options: ChecklistOptions = {}): string {
  const only = options.only ?? '';
  const selected = missions.filter((mission) => !only || mission.id === only);
  const lines: string[] = [];
  lines.push('# Campaign playtest worksheet', '');
  lines.push('Generated by `yarn qa:checklist` from `src/campaign/defs/campaign.ts`. Do not edit by hand: change the');
  lines.push(
    'mission and regenerate. The **sign-off is not written here**: `review/` is gitignored, so the verdict goes',
  );
  lines.push('in the table in `docs/design/human-playtest.md` (tracked).', '');
  lines.push('What the defs do **not** carry, and therefore cannot be checked by this generator: briefing art and its');
  lines.push(
    'provenance, the tutorial copy (`src/i18n/es.ts`), audio cues and the campaign unlock order. Those rows are',
  );
  lines.push('manual, and a mission change can leave them stale.', '');
  lines.push('## Before the manual pass', '');
  lines.push('- `yarn verify:fast` — types, lint, formatting, unit tests, build.');
  lines.push(
    '- `yarn test:e2e:slow` — the campaign playtests (real orders, no objective cheats) and the release playtest.',
  );
  lines.push(
    '- `yarn sim --matrix` — record the AI-vs-AI matrix. It is a baseline, not a gate: the committed run is not',
  );
  lines.push('  monotonic per difficulty yet (see `docs/ai-difficulty.md`), so do not treat it as a pass.');
  lines.push('');
  lines.push('## Campaign-level checks (once)', '');
  lines.push('- [ ] The menu shows the released entries per campaign and no planned entry is playable.');
  lines.push('- [ ] The unlock order opens missions in sequence and a finished mission unlocks the next.');
  lines.push('- [ ] The Codex is optional and never blocks a mission.');
  lines.push('- [ ] Every mission from the worksheet was played this pass, with the shipped settings and no cheats.');
  lines.push('');
  lines.push('## Per mission', '');

  for (const mission of selected) {
    const brief = missionBrief(mission);
    lines.push(`### ${mission.title} · ${mission.subtitle} (${mission.id})`, '');
    lines.push(`- Objectives: ${list(brief.required)}`);
    if (brief.grouped.length) lines.push(`- Alternatives (any one wins its group): ${list(brief.grouped)}`);
    lines.push(`- Optional: ${list(brief.optional)}`);
    lines.push(`- Fires: ${brief.fires ? `${brief.fires} point(s), lit by an objective` : '—'}`);
    lines.push(`- Prepared strikes: ${brief.strikes ? `${brief.strikes} (mines/galgas)` : '—'}`);
    lines.push(`- Scripted withdrawal: ${brief.withdrawals ? `yes (${brief.withdrawals})` : '—'}`);
    lines.push('');
    lines.push('- [ ] The briefing card, its text and its art match what the mission is about.');
    lines.push('- [ ] The tutorial or briefing explains the next useful action without blocking the player.');
    lines.push('- [ ] Every objective in the panel is readable and reaches a state (no objective stuck «pendiente»).');
    if (brief.grouped.length)
      lines.push('- [ ] Each alternative is a real choice: both paths are reachable and neither is a trap.');
    if (brief.optional.length)
      lines.push('- [ ] The optional goal is achievable without rushing the main line, and pays out.');
    if (brief.strikes) lines.push('- [ ] The prepared strike fires once, on the documented enemy, and is survivable.');
    if (brief.fires) lines.push('- [ ] The fire lights when its objective completes and stays lit.');
    if (brief.withdrawals) {
      lines.push('- [ ] The withdrawal pulls off the units it names, not the whole army, and the mission goes on.');
    }
    lines.push(
      '- [ ] Audio: the intro, the act cards and the victory have their cues; nothing is silent that should speak.',
    );
    lines.push('- [ ] Victory lands with the epilogue and a summary, and the next mission can be started from it.');
    lines.push('- [ ] Defeat is reachable and explained, not a silent loss.');
    lines.push('- [ ] Save mid-act, reload, and the objectives, units and timers come back.');
    lines.push('- [ ] 1280×720, 1600×900 and 1920×1080: no HUD overlap, clipping or unreadable panel.');
    lines.push('- [ ] No visible jank: terrain seams, units stuck, frame hitches.');
    lines.push('');
  }

  return lines.join('\n');
}

/**
 * Invariants the generator relies on. A mission with no non-optional objective cannot be won (a `group` member
 * counts); a mission listed twice would print two identical blocks.
 */
export function checklistProblems(missions: MissionDef[]): string[] {
  const problems: string[] = [];
  const seen = new Set<string>();
  for (const mission of missions) {
    if (seen.has(mission.id)) problems.push(`${mission.id}: listed twice`);
    seen.add(mission.id);
    if (!mission.objectives.some((objective) => !objective.optional)) {
      problems.push(`${mission.id}: no required objective, so it cannot be won`);
    }
  }
  return problems;
}
