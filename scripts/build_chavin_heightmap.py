#!/usr/bin/env python3
"""Generate the authored Chavín de Huántar heightfield (m2, 192 m map)."""

from __future__ import annotations

import base64
import math
from pathlib import Path

SIZE = 192
N = SIZE + 1
SITE_Y = 4.6
RIVER = 1.15
VALLEY = 3.3
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/model/defs/chavinHeightmap.ts'


def smoothstep(a: float, b: float, x: float) -> float:
    t = max(0.0, min(1.0, (x - a) / (b - a)))
    return t * t * (3.0 - 2.0 * t)


def noise(x: float, z: float) -> float:
    return (
        math.sin(x * 0.19 + z * 0.13) * 0.28
        + math.sin(x * 0.061 - z * 0.17 + 1.3) * 0.18
        + math.sin(x * 0.37 + z * 0.29 + 0.8) * 0.08
    )


def height(x: float, z: float) -> float:
    # Broad ceremonial terrace and the Mosna valley north of it.
    h = SITE_Y + 0.12 * noise(x, z)
    river_z = 38.0 + 1.8 * math.sin(x * 0.045 + 0.4)
    river_half = 3.4
    valley_half = 18.0
    dz = abs(z - river_z)
    if dz < river_half:
        h = RIVER
    elif dz < valley_half:
        t = smoothstep(river_half, valley_half, dz)
        h = RIVER + (VALLEY - RIVER) * t

    # The archaeological terrace and the southern base stay flat and connected.
    site = smoothstep(40.0, 47.0, x) * (1.0 - smoothstep(137.0, 145.0, x))
    site *= smoothstep(48.0, 56.0, z) * (1.0 - smoothstep(132.0, 140.0, z))
    base = smoothstep(38.0, 45.0, x) * (1.0 - smoothstep(73.0, 80.0, x))
    base *= smoothstep(104.0, 111.0, z) * (1.0 - smoothstep(130.0, 137.0, z))
    flat = max(site, base)
    h = h * (1.0 - 1.0 * flat) + SITE_Y * (1.0 * flat)

    # Highland ridges frame the Callejón de Conchucos, without cliffs at the site.
    north = smoothstep(14.0, 0.0, z) * (10.0 + 2.5 * math.sin(x * 0.09))
    west = smoothstep(22.0, 8.0, x) * (7.0 + 2.0 * math.sin(z * 0.11 + 0.7))
    east = smoothstep(150.0, 178.0, x) * (12.0 + 3.0 * math.sin(z * 0.1 + 1.4))
    south = smoothstep(150.0, 184.0, z) * (7.0 + 2.5 * math.sin(x * 0.12 + 0.2))
    h += north + west + east + south

    # A shallow quebrada east of the ceremonial centre.
    h -= 1.4 * math.exp(-((x - 132.0) / 5.0) ** 2) * smoothstep(50.0, 70.0, z) * (1.0 - smoothstep(110.0, 130.0, z))
    return max(0.9, h)


values = []
for iz in range(N):
    z = iz * SIZE / (N - 1)
    for ix in range(N):
        x = ix * SIZE / (N - 1)
        values.append(round(height(x, z) * 1000.0))

raw = bytearray()
for v in values:
    raw.extend(int(v).to_bytes(2, 'little'))
b64 = base64.b64encode(raw).decode('ascii')

OUT.write_text(
    '// Generated by scripts/build_chavin_heightmap.py. Do not edit by hand.\n'
    'export const CHAVIN_HEIGHTMAP_SIZE = ' + str(N) + ';\n'
    'export const CHAVIN_HEIGHTMAP_WORLD_SIZE = ' + str(SIZE) + ';\n'
    'export const CHAVIN_HEIGHTMAP_SCALE = 0.001;\n'
    'const B64 =\n  \'' + b64 + '\';\n'
    'function decode(): Float32Array {\n'
    '  const bin = atob(B64);\n'
    '  const out = new Float32Array(' + str(len(values)) + ');\n'
    '  for (let i = 0; i < out.length; i++) {\n'
    '    out[i] = (bin.charCodeAt(i * 2) | (bin.charCodeAt(i * 2 + 1) << 8)) * CHAVIN_HEIGHTMAP_SCALE;\n'
    '  }\n'
    '  return out;\n'
    '}\n'
    'export const CHAVIN_HEIGHTMAP = decode();\n',
    encoding='utf-8',
)
print(f'wrote {OUT} ({len(b64)} base64 chars, {len(values)} samples)')
