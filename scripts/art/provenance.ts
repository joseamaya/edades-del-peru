import fs from 'node:fs';
import path from 'node:path';
import type { ArtManifest, ArtManifestRecord } from '../../src/art/types';
import { getCiv } from '../../src/model/defs/civs';
import { getPeriod } from '../../src/model/defs/periods';
import { GENERATED_DIR } from './paths';

export const DISCLAIMER = 'No es una fotografía histórica: es un render 3D del proyecto.';

function row(record: ArtManifestRecord): string {
  const civ = getCiv(record.civilization)?.name ?? record.civilization;
  const period = getPeriod(record.period)?.name ?? String(record.period);
  const review = record.reviewed ? `reviewed${record.reviewer ? ` (${record.reviewer})` : ''}` : 'unreviewed';
  return `| \`${record.id}\` | ${record.type} | ${civ} | ${period} | ${record.region} | ${record.nature} | ${review} | \`${record.blender.camera}\` | \`${record.blender.confidence}\` | \`${record.blender.sourceSha256.slice(0, 12)}\` | [${path.basename(record.asset)}](${record.asset.replace(/^media\/generated\//, '')}) |`;
}

export function renderProvenance(manifest: ArtManifest): string {
  const lines = [
    '# Blender render assets',
    '',
    'This file is generated by `yarn art:blender`; do not edit it by hand.',
    'The canonical machine-readable manifest is `src/art/manifest.json`. The copy next to the assets is',
    'written for external tools and offline review.',
    '',
    `> ${DISCLAIMER}`,
    '',
    '## Source',
    '',
    '- Blender sources: `art-src/blender` (`.blend` in Git LFS; see `art-src/blender/caral/README.md`).',
    '- Source renders: `art-src/blender/renders/*.png`, verified by SHA-256 during ingestion.',
    '- Asset manifest: `art-src/blender/caral/caral_asset_manifest.csv`.',
    '- GIMP sources: `art-src/gimp/projects/*.xcf` in Git LFS; exports live in `art-src/gimp/exports`.',
    '- The manifest records the source paths and hashes; Blender/GIMP are authoring tools, not CI dependencies.',
    '',
    '## Assets',
    '',
    '| id | type | civ | period | region | nature | review | camera | confidence | source | file |',
    '|---|---|---|---|---|---|---|---|---|---|---|',
    ...(manifest.assets.length ? manifest.assets.map(row) : ['| — | — | — | — | — | — | — | — | — | — | — |']),
    '',
    '## Review',
    '',
    'Assets with `reviewed: false` are drafts. The game shows reviewed assets by default; use `?art=all`',
    'to preview drafts with a visible “Borrador sin revisar” caption.',
    '',
  ];
  return lines.join('\n');
}

export function writeProvenance(manifest: ArtManifest): void {
  fs.mkdirSync(GENERATED_DIR, { recursive: true });
  fs.writeFileSync(path.join(GENERATED_DIR, 'PROVENANCE.md'), renderProvenance(manifest));
  fs.writeFileSync(path.join(GENERATED_DIR, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
}
